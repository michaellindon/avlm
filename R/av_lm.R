#' Convert a Linear Model (lm) Object to Anytime-Valid lm (avlm)
#'
#' Converts an \code{lm} object into an anytime-valid version by storing a precision parameter
#' \code{g} as an attribute and updating the object's class. The resulting object supports anytime-valid inference.
#'
#' @param model An \code{lm} object from a linear model fit.
#' @param g A positive precision parameter for the anytime-valid mixture (see Lindon et al., 2026,
#' Section 4.3.1). It acts like a prior sample size: larger values favour smaller effects and give
#' narrower intervals at large \eqn{n}, at the cost of wider intervals at small \eqn{n}. Use
#' \code{\link{optimal_g}} to choose it for a target sample size. Default is 1.
#' @param vcov_estimator Optional character string specifying the type of heteroskedasticity-robust
#' standard errors to use. Must be one of \code{"HC0"}, \code{"HC1"}, \code{"HC2"}, or \code{"HC3"}.
#' If \code{NULL} (default), no robust variance estimation is applied. Cannot be combined with
#' \code{cluster}.
#' @param cluster Optional cluster specification for cluster-robust standard errors. Either a
#' vector of cluster identifiers, one per observation used in fitting \code{model} (e.g. a
#' respondent or unit id); a one-sided formula such as \code{~ cyl}; or a single column name
#' such as \code{"cyl"}. Formulas and column names are evaluated in the \code{data} the model
#' was fit with, and rows dropped from the fit (by \code{subset} or missing values) are dropped
#' from the clusters too. Only one-way clustering is supported. When supplied, standard errors are computed using
#' the CR1 cluster-robust sandwich estimator (scaled by \eqn{G/(G-1)}), and the
#' anytime-valid p-values and confidence intervals use \eqn{G - 1} (clusters minus one) as the
#' denominator degrees of freedom, rather than \eqn{n - p} (observations minus coefficients),
#' and the number of clusters \eqn{G} as the sample size, so \code{g} is on the cluster scale.
#' The cluster-robust e-values and confidence sequences are those of Lindon (2026).
#' Cannot be combined with \code{vcov_estimator}.
#' @param ... Additional arguments passed to or from other methods.
#'
#' @return An enhanced \code{lm} object of class \code{avlm} with anytime-valid inference capabilities.
#'
#' @examples
#' # Fit a linear model on the built-in mtcars dataset
#' fit <- lm(mpg ~ wt + hp, data = mtcars)
#'
#' # Convert the standard lm object to an anytime-valid avlm object
#' av_fit <- av(fit, g = 1)
#'
#' # Print the summary of the anytime-valid model
#' summary(av_fit)
#'
#' # With cluster-robust standard errors, clustering on number of cylinders
#' av_fit_cl <- av(fit, g = 1, cluster = ~ cyl)
#' summary(av_fit_cl)
#'
#' # Equivalent ways of specifying the clusters
#' av_fit_cl <- av(fit, g = 1, cluster = "cyl")
#' av_fit_cl <- av(fit, g = 1, cluster = mtcars$cyl)
#'
#' @references
#' Lindon, M., Ham, D. W., Tingley, M., and Bojinov, I. (2026). Anytime-Valid Inference in Linear Models with Applications to Regression-Adjusted Causal Inference. \emph{Journal of the American Statistical Association}. \doi{10.1080/01621459.2026.2692052}
#'
#' Lindon, M. (2026). Anytime-Valid Inference in Linear Models with Clustered Outcomes: Exact Multivariate Tests and Cluster-Robust Confidence Sequences. arXiv:2610.25613. \url{https://arxiv.org/abs/2610.25613}
#'
#' @export
av.lm <- function(model, g = 1, vcov_estimator = NULL, cluster = NULL, ...) {
  if (inherits(model, "glm")) {
    stop("av() supports linear models fit with lm(); objects of class \"glm\" are not supported.")
  }
  if (inherits(model, "mlm")) {
    stop("av() does not yet support multivariate responses (class \"mlm\").")
  }
  check_g(g)
  attr(model, "g") <- g

  cluster_f <- resolve_cluster_factor(model, cluster)

  if (!is.null(cluster_f) && !is.null(vcov_estimator)) {
    stop(
      "Specify only one of `vcov_estimator` (heteroskedasticity-robust) or `cluster` ",
      "(cluster-robust); not both."
    )
  }

  if (!is.null(vcov_estimator)) {
    # Validate choice
    valid_types <- c("HC0", "HC1", "HC2", "HC3")
    vcov_estimator <- match.arg(vcov_estimator, choices = valid_types)
  }
  attr(model, "vcov_estimator") <- vcov_estimator
  attr(model, "cluster") <- cluster_f
  class(model) <- c("avlm", class(model))


  return(model)
}

#' Summary Method for Anytime-Valid lm (avlm) Objects
#'
#' Computes a summary for an \code{avlm} object, a linear model enhanced with anytime-valid inference.
#' In addition to the standard \code{lm} summary statistics, the p-values for the coefficient tests are
#' recalculated using an anytime-valid method.
#'
#' @param object An \code{avlm} object generated by \code{av.lm}.
#' @param ... Additional arguments passed to or from other methods.
#'
#' @return A summary object of class \code{summary.avlm} that includes updated p-values for the coefficients.
#' @export
summary.avlm <- function(object, ...) {
  summ <- NextMethod()
  class(summ) <- c("summary.avlm", "summary.lm")

  g <- attr(object, "g")
  info <- av_vcov(object)
  beta <- info$coefficients
  se <- sqrt(diag(info$vcov))
  t <- beta / se

  # One coefficient at a time: d = 1 and the remaining k - 1 coefficients are nuisance.
  # The cluster-robust e-value (Lindon, 2026) has exponent G/2 = (nu + 1)/2, which is the
  # same as the d = 1 case of the heteroskedasticity-robust one (Lindon et al., 2026).
  summ$coefficients[names(beta), 2] <- se
  summ$coefficients[names(beta), 3] <- t
  summ$coefficients[names(beta), 4] <- p_G_t(log_G_t(t^2, info$nu, info$n, g))

  # Joint Wald test of every coefficient except the intercept.
  tested <- names(beta) != "(Intercept)"
  d <- sum(tested)
  if (d == 0) {
    summ$fstatistic <- NULL
  } else {
    V <- info$vcov[tested, tested, drop = FALSE]
    if (is_singular_vcov(V)) {
      # E = 1 (p-value 1) when the covariance of the tested coefficients is singular,
      # e.g. when there are no more clusters than tested coefficients.
      f <- NA_real_
      log_E <- 0
    } else {
      b <- beta[tested]
      Q <- as.numeric(crossprod(b, solve(V, b)))
      f <- Q / d
      log_E <- if (info$type == "CR1") log_E_CR(Q, d, info$n, g) else log_G_f(f, d, info$nu, info$n, g)
    }
    summ$fstatistic <- c(value = f, numdf = d, dendf = info$nu)
    attr(summ, "f_pvalue") <- p_G_f(log_E)
  }

  attr(summ, "g") <- g
  attr(summ, "vcov_estimator") <- if (info$type == "classical") NULL else info$type
  attr(summ, "cluster_G") <- info$G
  summ
}


#' Print Method for summary.avlm Objects
#'
#' Custom print method for \code{summary.avlm} objects that mimics the standard \code{summary.lm} output,
#' but replaces p-value column headers and includes anytime-valid annotations.
#' @param x An object of class \code{summary.avlm} containing the summary of an anytime-valid lm object.
#' @param digits The number of significant digits to use when printing. Defaults based on system options.
#' @param signif.stars Logical indicating whether significance stars should be printed.
#' @param ... Additional arguments passed to or from other methods.
#'
#' @return Invisibly returns the summary object.
#' @export
print.summary.avlm <- function(x, digits = max(3L, getOption("digits") - 3L), 
                               signif.stars = getOption("show.signif.stars"), ...) {
  # Don't call NextMethod() - we'll implement our own printing
  # that closely follows the standard summary.lm printing
  
  cat("\nCall:\n", paste(deparse(x$call), sep = "\n", collapse = "\n"), "\n\n", sep = "")
  
  # Print residuals
  resid <- x$residuals
  cat("Residuals:\n")
  if (length(resid) > 5) {
    rq <- quantile(resid)
    names(rq) <- c("Min", "1Q", "Median", "3Q", "Max")
    print(rq, digits = digits)
  } else {
    print(resid, digits = digits)
  }
  
  # Print coefficients
  cat("\nCoefficients:\n")
  regression_table <- capture.output({
    printCoefmat(x$coefficients, digits = digits, signif.stars = signif.stars, ...)
  })
  # Replace the p-value column header text
  output <- sub("Pr\\(>\\|t\\|\\)", "p value", regression_table)
  
  # Print the modified output
  cat(paste(output, collapse = "\n"))
  
  vcov_estimator = attr(x, "vcov_estimator")
  # Print residual standard error
  if(is.null(vcov_estimator)){
    cat("\nResidual standard error:", format(x$sigma, digits = digits), 
        "on", x$df[2], "degrees of freedom")
  }

  # Print NA handling message if needed
  if (nzchar(mess <- naprint(x$na.action))) 
    cat("\n (", mess, ")\n", sep = "")
  else cat("\n")
  
  # Print R-squared and F-statistic with custom p-value
  if (!is.null(x$fstatistic)) {
    cat("Multiple R-squared:  ", formatC(x$r.squared, digits = digits),
        ",\tAdjusted R-squared:  ", formatC(x$adj.r.squared, digits = digits), 
        "\n", sep = "")

    f <- x$fstatistic[1]
    d <- x$fstatistic[2]
    nu <- x$fstatistic[3]
    f_spvalue <- attr(x, "f_pvalue")
    
    # Print F-statistic with custom p-value
    cat("F-statistic:", formatC(f, digits = digits), 
        "on", d, "and", nu, "DF,  p-value:", 
        format.pval(f_spvalue, digits = digits), "\n")
  }
  
  cat("Anytime-Valid: TRUE (g = ", format(attr(x, "g"), digits = digits), ")\n", sep = "")
  if(!is.null(vcov_estimator)){
    cat("Robust Standard Error Type:", vcov_estimator, "\n")
    G <- attr(x, "cluster_G")
    if (!is.null(G)) {
      cat("Clusters:", G, "\n")
    }
  }

  invisible(x)
}


#' Confidence Intervals for Anytime-Valid lm (avlm) Objects
#'
#' Computes confidence intervals for the coefficients of an \code{avlm} object by adjusting
#' the standard errors using the precision parameter \code{g} and an anytime-valid approach.
#'
#' @param object An \code{avlm} object.
#' @param parm A specification of which parameters are to be given confidence intervals; can be a vector of numbers or names.
#' @param level The confidence level required for the intervals. Defaults to 0.95.
#' @param ... Additional arguments passed to or from other methods.
#'
#' @return A matrix with the lower and upper confidence limits for the specified parameters.
#' 
#' @examples
#' # Fit a simple linear model using the mtcars dataset
#' fit <- lm(mpg ~ wt + hp, data = mtcars)
#'
#' # Convert the standard lm object to an anytime-valid avlm object with precision parameter g = 1
#' av_fit <- av(fit, g = 1)
#'
#' # Calculate and print confidence intervals for the coefficients
#' conf_intervals <- confint(av_fit)
#' print(conf_intervals)
#' 
#' @export
confint.avlm <- function(object, parm, level = 0.95, ...) {
  info <- av_vcov(object)
  coefs <- coef(object)
  pnames <- names(coefs)
  if (missing(parm)) {
    parm <- pnames
  } else if (is.numeric(parm)) {
    parm <- pnames[parm]
  }

  alpha <- 1 - level
  radius <- t_radius(attr(object, "g"), info$n, alpha = alpha, nu = info$nu)
  se <- sqrt(diag(info$vcov))

  ci <- matrix(NA_real_, length(parm), 2L,
               dimnames = list(parm, paste(format(100 * c(alpha / 2, 1 - alpha / 2), trim = TRUE,
                                                 scientific = FALSE, digits = 3), "%")))
  est <- intersect(parm, names(se))
  ci[est, 1] <- coefs[est] - radius * se[est]
  ci[est, 2] <- coefs[est] + radius * se[est]
  ci
}

#' Covariance Matrix for Anytime-Valid lm (avlm) Objects
#'
#' Returns the covariance matrix used for anytime-valid inference: the classical one, or the
#' heteroskedasticity-robust or cluster-robust one requested in \code{\link{av.lm}}.
#'
#' @param object An \code{avlm} object.
#' @param complete Logical; if \code{TRUE} (the default), aliased coefficients are included
#' with \code{NA} rows and columns, as in \code{\link[stats]{vcov}}.
#' @param ... Unused.
#'
#' @return A covariance matrix.
#' @examples
#' fit <- av(lm(mpg ~ wt + hp, data = mtcars), cluster = ~ cyl)
#' vcov(fit)
#' @export
vcov.avlm <- function(object, complete = TRUE, ...) {
  V <- av_vcov(object)$vcov
  if (!complete) return(V)
  pnames <- names(coef(object))
  out <- matrix(NA_real_, length(pnames), length(pnames), dimnames = list(pnames, pnames))
  out[rownames(V), colnames(V)] <- V
  out
}
